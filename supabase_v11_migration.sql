alter table public.profiles
  add column if not exists home_equipment text[] not null default '{}',
  add column if not exists photo_storage_path text;

create table if not exists public.progress_photos (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  photo_type text not null check (photo_type in ('frente','lado','costas')),
  storage_path text not null,
  taken_at timestamptz not null default now(),
  notes text
);

alter table public.progress_photos enable row level security;

drop policy if exists "Users can view own progress photos" on public.progress_photos;
drop policy if exists "Users can insert own progress photos" on public.progress_photos;
drop policy if exists "Users can delete own progress photos" on public.progress_photos;

create policy "Users can view own progress photos"
on public.progress_photos for select to authenticated
using (auth.uid() = user_id);

create policy "Users can insert own progress photos"
on public.progress_photos for insert to authenticated
with check (auth.uid() = user_id);

create policy "Users can delete own progress photos"
on public.progress_photos for delete to authenticated
using (auth.uid() = user_id);

insert into storage.buckets (id,name,public)
values ('profile-photos','profile-photos',true)
on conflict (id) do update set public=true;

insert into storage.buckets (id,name,public)
values ('progress-photos','progress-photos',false)
on conflict (id) do nothing;

drop policy if exists "Profile photos own folder insert" on storage.objects;
drop policy if exists "Profile photos own folder update" on storage.objects;
drop policy if exists "Progress photos own folder select" on storage.objects;
drop policy if exists "Progress photos own folder insert" on storage.objects;
drop policy if exists "Progress photos own folder delete" on storage.objects;

create policy "Profile photos own folder insert"
on storage.objects for insert to authenticated
with check (
  bucket_id='profile-photos'
  and (storage.foldername(name))[1] = auth.uid()::text
);

create policy "Profile photos own folder update"
on storage.objects for update to authenticated
using (
  bucket_id='profile-photos'
  and (storage.foldername(name))[1] = auth.uid()::text
)
with check (
  bucket_id='profile-photos'
  and (storage.foldername(name))[1] = auth.uid()::text
);

create policy "Progress photos own folder select"
on storage.objects for select to authenticated
using (
  bucket_id='progress-photos'
  and (storage.foldername(name))[1] = auth.uid()::text
);

create policy "Progress photos own folder insert"
on storage.objects for insert to authenticated
with check (
  bucket_id='progress-photos'
  and (storage.foldername(name))[1] = auth.uid()::text
);

create policy "Progress photos own folder delete"
on storage.objects for delete to authenticated
using (
  bucket_id='progress-photos'
  and (storage.foldername(name))[1] = auth.uid()::text
);
